const DEVANAGARI_DIGITS = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];

export function toDisplayDigits(input: string | number, numeralSystem: NumeralSystem): string {
  const str = String(input);
  if (numeralSystem !== 'hi') return str;
  return str.replace(/\d/g, (d) => DEVANAGARI_DIGITS[Number(d)] || d);
}

export function formatINR(amount: number, numeralSystem: NumeralSystem = 'en'): string {
  const isNeg = amount < 0;
  const formatted = Math.abs(Math.round(amount)).toLocaleString('en-IN');
  const out = `${isNeg ? '-₹' : '₹'}${formatted}`;
  return toDisplayDigits(out, numeralSystem);
}

const MONTH_NAMES: Record<Language, string[]> = {
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
  hi: ['जन', 'फ़र', 'मार्च', 'अप्रै', 'मई', 'जून', 'जुला', 'अग', 'सित', 'अक्टू', 'नव', 'दिस'],
  ur: ['جنوری', 'فروری', 'مارچ', 'اپریل', 'مئی', 'جون', 'جولائی', 'اگست', 'ستمبر', 'اکتوبر', 'نومبر', 'دسمبر'],
};

export function formatMonthKey(monthKey: string, lang: Language = 'en', numeralSystem: NumeralSystem = 'en'): string {
  if (!monthKey || monthKey.length < 7) return monthKey;
  const y = monthKey.slice(0, 4);
  const mIdx = Number(monthKey.slice(5, 7)) - 1;
  const mLabel = MONTH_NAMES[lang]?.[mIdx] || MONTH_NAMES.en[mIdx] || monthKey;
  return toDisplayDigits(`${mLabel} ${y}`, numeralSystem);
}

